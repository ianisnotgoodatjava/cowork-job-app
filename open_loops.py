"""Threads where someone asked you something and it is still unanswered.

This is the signal the rest of the project misses. reoutreach finds threads
that went quiet; follow_up finds outreach that got no reply. Neither catches
the opposite and more valuable case -- a real person replied, asked for
something, and the ball has been sitting in your court since. Dan Rubenstein
at Fitch asked "do you know who the hiring manager or HR contact are?" and
that question sat for a day while cold emails were written to strangers.

The naive version of this -- "whoever wrote last" -- was wrong on all three
threads it found, and every failure is worth keeping as a rule:

  ProShares      Kieran Kirwan's last line was "Best of luck", after he had
                 already taken the call and forwarded the resume. A closing
                 pleasantry is the end of a conversation, not an open one.
  ABI Research   the "message" was a [like] reaction to Ian's thank-you.
  NBCUniversal   the message was "Accepted: Ian's Inquiry about Treasury",
                 a calendar response generated by Outlook.

So the test is not who spoke last. It is whether the last thing they said
actually asks for something: a question mark, or a request phrase, in text
that is not a reaction, a calendar response, or a sign-off.
"""

import datetime
import re
from email.utils import parsedate_to_datetime

import gmail_client
import interview_signals
from config import ME_RE

# Outlook and Gmail generate these on the recipient's behalf. Nobody typed
# them, so nothing in them is addressed to you.
_NOT_A_MESSAGE_RE = re.compile(
    r"^(accepted|declined|tentative|tentatively accepted|canceled|cancelled|"
    r"updated invitation|invitation):|reacted to your message|^\[like\]", re.I)

# A reply is wanted when they ask, not when they are being polite.
_ASKS_RE = re.compile(
    r"\?|\b(let me know|could you|can you|would you|please send|please share|"
    r"do you have|are you available|what times?|when (are|would) you|"
    r"send me|share your|point me|any chance|happy to (chat|speak|connect)|"
    r"i(?:'| a)m free|does .{0,20}work for you)\b", re.I)

# Sign-offs that close a thread. A "?" anywhere still wins over these.
_CLOSING_RE = re.compile(
    r"^\W*(great|thanks|thank you|glad to hear|best of luck|good luck|"
    r"sounds good|will do|no problem|congrats|congratulations|"
    r"you(?:'| a)re welcome)\b[\s\S]{0,80}$", re.I)


def _when(msg: dict):
    try:
        stamp = parsedate_to_datetime(msg.get("date", ""))
    except (TypeError, ValueError):
        return None
    if stamp is None:
        return None
    return (stamp.replace(tzinfo=datetime.timezone.utc)
            if stamp.tzinfo is None else stamp)


def _visible(body: str) -> str:
    """The part they actually typed, without the quoted thread beneath."""
    text = interview_signals.plain_text(body or "")
    text = re.split(r"\n\s*(?:On .{0,60}wrote:|-----Original|_{10,}|From: )",
                    text)[0]
    # URLs go before anything is matched. Proofpoint rewrites every link as
    # ".../v2/url?u=..." and that "?" read as a question, so a signature block
    # made a closing "Best of luck" look like an open question.
    text = re.sub(r"https?://\S+|\bwww\.\S+", " ", text)
    # Phone numbers and address lines in signatures are noise too.
    text = re.sub(r"\b(?:DIRECT|Cell|Phone|Tel)\b[^\n]*", " ", text, flags=re.I)
    return re.sub(r"[ \t]+", " ", text).strip()


def needs_reply(msg: dict) -> str:
    """Why this message wants an answer, or '' if it does not."""
    subject = (msg.get("subject") or "").strip()
    if _NOT_A_MESSAGE_RE.search(subject):
        return ""
    body = _visible(msg.get("body", ""))
    if not body or _NOT_A_MESSAGE_RE.search(body[:120]):
        return ""
    # Sign-offs are short and have no question in them.
    if len(body) < 240 and _CLOSING_RE.match(body) and "?" not in body:
        return ""
    match = _ASKS_RE.search(body)
    if not match:
        return ""
    where = body[max(0, match.start() - 70):match.start() + 90]
    return re.sub(r"\s+", " ", where).strip()


def scan(days_back: int = 120, limit: int = 900) -> list[dict]:
    """Threads whose last inbound message asks something you have not answered."""
    messages = gmail_client.search_messages(
        f"newer_than:{days_back}d -in:chats", max_results=limit,
        include_body=True)

    threads: dict[str, list] = {}
    for msg in messages:
        if _when(msg):
            threads.setdefault(msg.get("threadId"), []).append(msg)

    now = datetime.datetime.now(datetime.timezone.utc)
    out = []
    for thread in threads.values():
        # The search is only a candidate generator. It pages through hundreds
        # of messages and drops some to read errors, so a thread arrives here
        # partially fetched and its apparent last message may not be the real
        # one. Webster Bank looked like an unanswered question that way; the
        # actual last message in that thread was Ian's own reply. Every
        # candidate is re-fetched in full before it is judged.
        try:
            full = gmail_client.get_thread(thread[0].get("threadId"),
                                           include_body=True)
        except Exception:
            continue
        full = [m for m in full if _when(m)]
        if not full:
            continue
        full.sort(key=_when)
        thread, last = full, full[-1]
        sender = last.get("from", "")
        if ME_RE.search(sender):
            continue
        if interview_signals.is_automated(sender, last.get("subject", "")):
            continue
        # Only threads you are actually part of: something you sent must
        # precede their message, or this is a broadcast.
        if not any(ME_RE.search(m.get("from", "")) for m in thread[:-1]):
            continue
        asked = needs_reply(last)
        if not asked:
            continue
        out.append({
            "days": (now - _when(last)).days,
            "from": sender,
            "subject": last.get("subject", ""),
            "asked": asked,
            "threadId": last.get("threadId"),
        })
    out.sort(key=lambda r: -r["days"])
    return out


def run(days_back: int = 120) -> None:
    loops = scan(days_back)
    if not loops:
        print("No unanswered questions. Every thread is on their side.")
        return
    print(f"{len(loops)} thread(s) waiting on you:\n")
    for loop in loops:
        print(f"  {loop['days']:3d}d  {loop['from'][:46]}")
        print(f"        {loop['subject'][:66]}")
        print(f"        asked: \"{loop['asked'][:90]}\"\n")
